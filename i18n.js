  let currentLang = 'en';

  function detectBrowserLanguage() {
    try {
      const lang = (navigator.language || navigator.userLanguage || 'en').slice(0, 2).toLowerCase();
      return SUPPORTED_LANGS.includes(lang) ? lang : 'en';
    } catch {
      return 'en';
    }
  }

  async function loadLanguage() {
    try {
      const data = await chrome.storage.local.get([STORAGE_KEY]);
      const settings = data[STORAGE_KEY] || {};
      if (settings.ui_language && SUPPORTED_LANGS.includes(settings.ui_language)) {
        currentLang = settings.ui_language;
      } else {
        currentLang = detectBrowserLanguage();
      }
    } catch {
      currentLang = detectBrowserLanguage();
    }
    return currentLang;
  }

  async function setLanguage(lang) {
    if (!SUPPORTED_LANGS.includes(lang)) return;
    currentLang = lang;
    try {
      const data = await chrome.storage.local.get([STORAGE_KEY]);
      const settings = data[STORAGE_KEY] || {};
      settings.ui_language = lang;
      await chrome.storage.local.set({ [STORAGE_KEY]: settings });
    } catch {}
  }

  function t(key) {
    return translations[currentLang]?.[key] ?? translations['en']?.[key] ?? key;
  }

  function applyTranslations(root) {
    const r = root || document;
    r.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.dataset.i18n;
      el.textContent = t(key);
    });
    r.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      el.placeholder = t(el.dataset.i18nPlaceholder);
    });
    r.querySelectorAll('[data-i18n-title]').forEach((el) => {
      el.title = t(el.dataset.i18nTitle);
    });
    r.querySelectorAll('[data-i18n-aria-label]').forEach((el) => {
      el.setAttribute('aria-label', t(el.dataset.i18nAriaLabel));
    });
    r.querySelectorAll('[data-i18n-html]').forEach((el) => {
      el.innerHTML = t(el.dataset.i18nHtml);
    });
  }

  globalThis.TAi18n = {
    t,
    loadLanguage,
    setLanguage,
    applyTranslations,
    detectBrowserLanguage,
    SUPPORTED_LANGS,
    get currentLang() { return currentLang; },
  };
